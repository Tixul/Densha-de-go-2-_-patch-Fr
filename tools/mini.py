# accents : (lettre de base, motif ligne 0 sur la largeur de la lettre)
ACC = {'É': ('E', '.#.'), 'È': ('E', '#..'), 'Ê': ('E', '#.#'), 'Ë': ('E', '#.#'), 'À': ('A', '#..'),
       'Â': ('A', '#.#'), 'Î': ('I', '#'), 'Ï': ('I', '#'), 'Ô': ('O', '#.#'), 'Û': ('U', '#.#'),
       'Ù': ('U', '#..'), 'Ü': ('U', '#.#')}


def glyphe(ch):
    """-> 8 lignes (chaînes) de la lettre."""
    ch = ch.upper() if ch not in ('×',) else ch
    if ch in ('É', 'È', 'Ê', 'Ë', 'À', 'Â', 'Î', 'Ï', 'Ô', 'Û', 'Ù', 'Ü'):
        b, a = ACC[ch]
        g = G[b]
        w = len(g[0])
        a = (a + '.' * w)[:w] if w >= len(a) else a[:w]
        return [a, '.' * w] + g + ['.' * w]
    if ch == 'Ç':
        g = G['C']
        return ['...', '...'] + g + ['.#.']
    if ch == 'Œ':
        g = ['.####', '#.#..', '#.##.', '#.#..', '.####']
        return ['.....', '.....'] + g + ['.....']
    g = G.get(ch, G['?'])
    w = len(g[0])
    return ['.' * w, '.' * w] + g + ['.' * w]


def texte(s, espace=1):
    rows = [''] * 8
    for i, ch in enumerate(s):
        g = glyphe(ch)
        for y in range(8):
            rows[y] += ('.' * espace if i else '') + g[y]
    bm = [[1 if c == '#' else 0 for c in r] for r in rows]
    return bm, len(rows[0])
